import fs from 'node:fs';
import path from 'node:path';
import { ToolError } from '../../core/errors.ts';
import { isFile } from '../../core/fs.ts';
import {
  checkRef,
  ensureCommit,
  exportCommit,
  exportFolderName,
  fetchSource,
  isCompleteExport,
  resolveRef,
  shortCommitLength,
  withBareClone,
  type GitSource,
  type LockWait,
} from './git.ts';
import type { LockedSource } from './lock.ts';

/** Exports live in the consumer's gitignored local folder, one per pinned commit. */
export const sourcesDirectory = (configRoot: string): string =>
  path.join(configRoot, '.agents', 'local', 'sources');

export type GitSourceRequest = {
  source: GitSource;
  ref: string | undefined;
  locked: LockedSource | undefined;
  /** Fetch and resolve the ref again even when the lock already pins it (`skills update`). */
  refresh: boolean;
  /** `--locked`: fail rather than change the pin. */
  frozen: boolean;
  dryRun: boolean;
  toolsHome: string;
  sourcesDir: string;
  wait: LockWait;
};

export type PreparedGitSource = {
  /** The export to link from, or undefined when a dry run cannot see it yet. */
  root: string | undefined;
  /** The pin to keep in the lock; undefined when a dry run would resolve it. */
  pin: LockedSource | undefined;
  /** True when this run wrote the export, so a failed sync can take it back. */
  created: boolean;
  messages: string[];
};

const describeRef = (ref: string | undefined): string =>
  ref === undefined ? 'the default branch' : `'${ref}'`;

const pinnedEntry = (ref: string | undefined): { ref?: string } =>
  ref === undefined ? {} : { ref };

const short = (commit: string): string => commit.slice(0, shortCommitLength);

/** Does the lock entry still answer the config? The config's ref is the request; the lock its answer. */
export const lockMatches = (
  locked: LockedSource | undefined,
  ref: string | undefined,
): locked is LockedSource => locked !== undefined && locked.ref === ref;

/** Exports hold another repo's files: keep them out of the consumer's commits even without a rule. */
const ignoreSourcesDirectory = (sourcesDir: string): void => {
  const gitignore = path.join(sourcesDir, '.gitignore');
  if (!isFile(gitignore)) {
    fs.mkdirSync(sourcesDir, { recursive: true });
    fs.writeFileSync(
      gitignore,
      '# Generated by agentic-tools `skills sync`: exports of pinned git sources.\n*\n',
      'utf8',
    );
  }
};

/**
 * Pin, fetch and export one git source. With a matching pin and a complete export it touches
 * neither the network nor the bare clone, so a synced project keeps working offline.
 */
export const prepareGitSource = (
  request: GitSourceRequest,
): PreparedGitSource => {
  const { source, ref } = request;
  checkRef(source.from, ref);
  const pinned = lockMatches(request.locked, ref) && !request.refresh;
  if (!pinned && request.frozen) {
    throw new ToolError(
      `The lock does not pin ${describeRef(ref)} for '${source.from}'. Run skills sync without ` +
        '--locked to update .agents/agentic-tools.lock, and commit it.',
    );
  }

  const exportFolder = (commit: string): string =>
    path.join(request.sourcesDir, exportFolderName(source, commit));
  const pinnedCommit =
    pinned ? (request.locked as LockedSource).commit : undefined;

  if (pinnedCommit !== undefined) {
    const folder = exportFolder(pinnedCommit);
    if (isCompleteExport(folder, pinnedCommit)) {
      return {
        root: folder,
        pin: { ...pinnedEntry(ref), commit: pinnedCommit },
        created: false,
        messages: [],
      };
    }
    if (request.dryRun) {
      return {
        root: undefined,
        pin: { ...pinnedEntry(ref), commit: pinnedCommit },
        created: false,
        messages: [
          `Would export ${source.from} at ${short(pinnedCommit)} to ${folder}`,
        ],
      };
    }
  } else if (request.dryRun) {
    return {
      root: undefined,
      pin: undefined,
      created: false,
      messages: [
        `Would fetch ${source.url}, pin ${describeRef(ref)} in the lock, and export it`,
      ],
    };
  }

  const messages: string[] = [];
  return withBareClone(
    source,
    request.toolsHome,
    request.wait,
    (gitDir, cloned): PreparedGitSource => {
      if (cloned) {
        messages.push(`Cloned ${source.url} into ${gitDir}`);
      }
      let commit: string;
      if (pinnedCommit === undefined) {
        if (!cloned) {
          fetchSource(gitDir);
          messages.push(`Fetched ${source.url}`);
        }
        commit = resolveRef(gitDir, source, ref);
        messages.push(`Pinned ${source.from} ${describeRef(ref)} at ${commit}`);
      } else {
        commit = pinnedCommit;
        if (ensureCommit(gitDir, source, commit)) {
          messages.push(`Fetched ${source.url}`);
        }
      }
      const folder = exportFolder(commit);
      ignoreSourcesDirectory(request.sourcesDir);
      const created = exportCommit({
        gitDir,
        source,
        commit,
        folder,
        wait: request.wait,
      });
      if (created) {
        messages.push(
          `Exported ${source.from} at ${short(commit)} to ${folder}`,
        );
      }
      return {
        root: folder,
        pin: { ...pinnedEntry(ref), commit },
        created,
        messages,
      };
    },
  );
};
